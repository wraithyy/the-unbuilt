import { chromium } from '@playwright/test'
const out = process.argv[2]
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } })
const errs = []
page.on('pageerror', (e) => errs.push(e.message))
await page.goto((process.env.URL ?? 'http://localhost:5173/?debug'))
await page.evaluate(() => localStorage.clear())
await page.reload()
await page.getByRole('button', { name: 'Enter' }).click()
await page.waitForTimeout(500)
const g = (fn) => page.evaluate(fn)
const state = () => g(() => { const x = window.__unbuilt; return { pos: x.player.pos.toArray().map(n=>+n.toFixed(2)), area: x.area, flags: [...x.flags.all], cube: x.cubes[0].pos.toArray().map(n=>+n.toFixed(2)), creeping: x.cubes[0].creeping } })
// face south, walk backwards (north) through the drawn door
await g(() => { window.__unbuilt.player.yaw = Math.PI })
await page.waitForTimeout(300)
await page.keyboard.down('KeyS')
await page.waitForTimeout(1900)
await page.keyboard.up('KeyS')
console.log('after backwards walk', JSON.stringify(await state()))
await page.waitForTimeout(9000)
console.log('after waiting', JSON.stringify(await state()))
await page.screenshot({ path: out + '-vest.png' })
await g(() => { window.__unbuilt.player.yaw = 0 })
await page.waitForTimeout(400)
await page.screenshot({ path: out + '-vest-north.png' })
await page.keyboard.down('KeyW')
await page.waitForTimeout(4500)
await page.keyboard.up('KeyW')
console.log('after walk north', JSON.stringify(await state()))
await page.screenshot({ path: out + '-atrium.png' })
console.log('errors', errs)
await browser.close()
